    random.seed(42)  # remove or change this line if you want different numbers on each run

    episode_counts = [100, 500, 1000, 5000, 10000]
    eval_games = 1000  # number of games used to measure Win/Loss/Draw after each training run

    print(f"{'Episodes':>10} | {'Win %':>7} | {'Loss %':>7} | {'Draw %':>7} | Behaviour")
    print("-" * 95)

    results = []
    for ep in episode_counts:
        agent_x, agent_o = train(ep)
        stats = evaluate(agent_x, agent_o, games=eval_games)
        behaviour = describe_behaviour(stats, ep)
        results.append((ep, stats, behaviour))
        print(f"{ep:>10} | {stats['win_pct']:6.1f}% | {stats['loss_pct']:6.1f}% | "
              f"{stats['draw_pct']:6.1f}% | {behaviour}")